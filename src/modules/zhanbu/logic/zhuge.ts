// 扩到 384（每条循环 ~7 次）
const ALL_QIAN: ZhugeQian[] = []
for (let i = 0; i < 384; i++) {
  const base = QIAN_POOL[i % QIAN_POOL.length]!
  const score = 30 + ((i * 13) % 71)
  const scores = {
    career: 30 + ((i * 11) % 71),
    wealth: 30 + ((i * 17) % 71),
    relationship: 30 + ((i * 23) % 71),
    health: 30 + ((i * 29) % 71),
    social: 30 + ((i * 31) % 71),
  }
  ALL_QIAN.push({ num: i + 1, ...base, score, scores })
}

/**
 * 抽取签
 * 用 (num1, num2, num3) 三个数字或自动随机
 */
export function drawZhuge(num1?: number, num2?: number, num3?: number): ZhugeQian {
  const a = num1 ?? Math.floor(Math.random() * 9) + 1
  const b = num2 ?? Math.floor(Math.random() * 9) + 1
  const c = num3 ?? Math.floor(Math.random() * 9) + 1
  const num = ((a * 100 + b * 10 + c) % 384) + 1
  return ALL_QIAN[num - 1]
}

