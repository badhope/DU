// 合并
const ALL_ZHENJU = [...ZHENJU_DB, ...EXT_ZHENJU]

/**
 * 根据心境推荐
 */
export function recommendByXinjing(xj: Xinjing, limit = 5): Zhenju[] {
  return ALL_ZHENJU.filter((z) => z.xinjing.includes(xj))
    .sort((a, b) => b.weight - a.weight)
    .slice(0, limit)
}

/**
 * 每日一句（基于日期稳定）
 */
export function dailyZhenju(date?: Date): Zhenju {
  const d = date || new Date()
  const day = d.getDate() + d.getMonth() * 31
  return ALL_ZHENJU[day % ALL_ZHENJU.length]
}

/**
 * 随机一句
 */
export function randomZhenju(): Zhenju {
  return ALL_ZHENJU[Math.floor(Math.random() * ALL_ZHENJU.length)]
}

/**
 * 按 category 分类
 */
export function byCategory(cat: Zhenju['category']): Zhenju[] {
  return ALL_ZHENJU.filter((z) => z.category === cat)
}
