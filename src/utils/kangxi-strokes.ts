/**
 * 构建去重后的康熙字典笔画表
 */
function buildTable(): Record<string, number> {
  const table: Record<string, number> = {}
  const seen = new Set<string>()
  for (const [word, strokes] of [...RAW_STROKES, ...BAGUA, ...TIANGAN_DIZHI, ...COMPLEX_SURNAMES]) {
    if (seen.has(word)) continue
    seen.add(word)
    table[word] = strokes
  }
  return table
}

export const KANGXI_STROKES: Record<string, number> = buildTable()

/**
 * 查康熙字典笔画（找不到则用简化笔画）
 */
export function kangxiStrokes(ch: string): number {
  if (KANGXI_STROKES[ch] !== undefined) return KANGXI_STROKES[ch]
  return chineseStrokesApprox(ch)
}

/**
 * 简体中文笔画近似（无康熙字典数据时使用）
 */
function chineseStrokesApprox(ch: string): number {
  const code = ch.charCodeAt(0)
  if (code < 0x4e00 || code > 0x9fff) return 1
  return ((code - 0x4e00) % 30) + 3
}

/**
 * 完整姓名按字逐个查康熙笔画
 */
export function nameStrokes(name: string): number[] {
  return name.split('').map(c => kangxiStrokes(c))
}
