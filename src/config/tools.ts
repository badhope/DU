/**
 * 按分类分组工具
 */
export function getToolsByCategory(): Array<{ category: Category; tools: Tool[] }> {
  return CATEGORIES.map((cat) => ({
    category: cat,
    tools: TOOLS.filter((t) => t.category === cat.key),
  })).filter((g) => g.tools.length > 0)
}

/**
 * 快速查找工具
 */
export function findTool(key: string): Tool | undefined {
  return TOOLS.find((t) => t.key === key)
}

