/**
 * 选建议。
 *
 * 有匹配条件且命中的优先；同一领域内用 seed 轮换，避免同一问题反复问
 * 永远看到同一条。
 */
export function adviceFor(domain: ReadingDomain, q: QuestionReading, seed: number): string {
  const pool = BY_DOMAIN[domain] ?? BY_DOMAIN.general
  const specific = pool.filter((a) => a.when?.(q))
  const rest = pool.filter((a) => !a.when)
  const ordered = specific.length ? [...specific, ...rest] : pool
  const pick = ordered[Math.abs(seed) % ordered.length] ?? ordered[0]
  return pick!.text
}

/** 供测试与界面枚举 */
export const ADVICE_DOMAINS = Object.keys(BY_DOMAIN) as ReadingDomain[]
export const adviceCount = (domain: ReadingDomain): number => BY_DOMAIN[domain].length
