#!/usr/bin/env python3
"""Generate the dynamic SVG assets that live under ``assets/effects``.

The script is responsible for two SVGs:

* ``project-showcase.svg`` - highlights the user's top repositories with
  star/fork totals and links to the full project list.
* ``stats-panel.svg`` - a tech stack overview with a language distribution
  bar chart.

Both SVGs are regenerated by the ``Update SVG Stats`` workflow on a daily
schedule. The implementation prefers real data from the GitHub REST API and
gracefully falls back to sensible defaults when the API rate limit is hit
or the network is unavailable.
"""

