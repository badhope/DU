logger = get_logger("scripts.generate_svg")

DEFAULT_LANGUAGE_DISTRIBUTION = {
    "Python": 35.0,
    "TypeScript": 28.0,
    "JavaScript": 20.0,
    "Java": 17.0,
}

MAX_PROJECTS_IN_SHOWCASE = 2
MAX_LANGUAGES_IN_PANEL = 6


def fetch_projects(client: GitHubClient, username: str) -> List[Dict[str, Any]]:
    """Fetch the user's top repositories as small summaries."""
    try:
        repos = list(
            client.iter_user_repos(
                username=username,
                type="owner",
                sort="stargazers",
                direction="desc",
            )
        )
    except (NetworkError, GitHubAPIError) as exc:
        logger.error("Failed to fetch repositories: %s", exc)
        return []

    filtered = GitHubClient.filter_repositories(repos)
    sorted_repos = GitHubClient.sort_repositories(
        filtered, by="stargazers_count", descending=True
    )
    return [GitHubClient.extract_repo_summary(r) for r in sorted_repos]


def fetch_languages(
    client: GitHubClient, username: str
) -> Dict[str, float]:
    """Return the percentage distribution of languages across all repos."""
    try:
        totals = client.iter_user_repos_languages(username)
    except (NetworkError, GitHubAPIError) as exc:
        logger.error("Failed to fetch language stats: %s", exc)
        return dict(DEFAULT_LANGUAGE_DISTRIBUTION)

    total_bytes = sum(totals.values())
    if total_bytes == 0:
        return dict(DEFAULT_LANGUAGE_DISTRIBUTION)

    percentages = {
        lang: round((count / total_bytes) * 100, 1)
        for lang, count in sorted(
            totals.items(), key=lambda item: item[1], reverse=True
        )[:MAX_LANGUAGES_IN_PANEL]
    }
    return percentages or dict(DEFAULT_LANGUAGE_DISTRIBUTION)


