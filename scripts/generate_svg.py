def _build_language_bar(language: str, percentage: float, y_offset: int) -> str:
    color = language_color(language)
    bar_width = min(int(percentage * 3.5), 300)
    return (
        f'<rect x="50" y="{y_offset}" width="{bar_width}" height="20" rx="3" '
        f'fill="{color}" opacity="0.8"/>\n'
        f'  <text x="{50 + bar_width / 2}" y="{y_offset + 14}" '
        f'text-anchor="middle" fill="#ffffff" font-size="11" '
        f'font-family="Arial, sans-serif">{language} {percentage}%</text>'
    )


def generate_stats_panel_svg(
    language_stats: Dict[str, float],
    output_path: Path,
) -> None:
    """Render ``stats-panel.svg`` to ``output_path``."""
    bars: List[str] = []
    y_offset = 120
    for language, percentage in list(language_stats.items())[:MAX_LANGUAGES_IN_PANEL]:
        bars.append(_build_language_bar(language, percentage, y_offset))
        y_offset += 25
    svg = _stats_panel_template().format(language_bars="\n  ".join(bars))
    output_path.write_text(svg, encoding="utf-8")
    logger.info("Wrote stats panel SVG to %s", output_path)


def main() -> int:
    """Command line entry point."""
    logger.info("=" * 60)
    logger.info("Dynamic SVG Generator")
    logger.info("=" * 60)

    try:
        config = get_config()
    except ConfigError as exc:
        logger.error("Invalid configuration: %s", exc)
        return 2

    client = GitHubClient(config.github)
    username = config.github.username

    output_dir = Path(config.svg.output_dir)
    if not output_dir.is_absolute():
        output_dir = Path(__file__).resolve().parent.parent / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    projects = fetch_projects(client, username)
    if not projects:
        logger.warning("No projects to render; using empty showcase")

    language_stats = fetch_languages(client, username)

    generate_project_showcase_svg(
        projects,
        output_dir / "project-showcase.svg",
        username=username,
    )
    generate_stats_panel_svg(
        language_stats,
        output_dir / "stats-panel.svg",
    )

    logger.info("SVG generation complete")
    return 0


# Backwards-compatible class preserved for older tests / imports
class SVGGenerator:  # pragma: no cover - thin wrapper for legacy callers
    """Thin façade around the module level functions, kept for compatibility."""

    def __init__(self, github_token: str = None):
        from scripts.common.config import GitHubConfig

        config = GitHubConfig(token=github_token or os.getenv("GITHUB_TOKEN"))
        self.client = GitHubClient(config)

    def fetch_repo_stats(self, owner: str, repo: str) -> Dict[str, Any]:
        try:
            payload = self.client.get_repo(owner, repo)
        except (NetworkError, GitHubAPIError):
            return {
                "stars": 0,
                "forks": 0,
                "issues": 0,
                "language": "Unknown",
                "description": "",
                "updated_at": "",
            }
        return {
            "stars": payload.get("stargazers_count", 0),
            "forks": payload.get("forks_count", 0),
            "issues": payload.get("open_issues_count", 0),
            "language": payload.get("language", "Unknown"),
            "description": payload.get("description", ""),
            "updated_at": payload.get("updated_at", ""),
        }

    def fetch_user_stats(self, username: str) -> Dict[str, Any]:
        try:
            payload = self.client.get_user(username)
        except (NetworkError, GitHubAPIError):
            return {
                "public_repos": 0,
                "followers": 0,
                "following": 0,
                "created_at": "",
            }
        return {
            "public_repos": payload.get("public_repos", 0),
            "followers": payload.get("followers", 0),
            "following": payload.get("following", 0),
            "created_at": payload.get("created_at", ""),
        }

    def fetch_language_stats(self, username: str) -> Dict[str, float]:
        return fetch_languages(self.client, username)

    def generate_project_showcase_svg(
        self, projects: List[Dict[str, Any]], output_path: str
    ) -> None:
        generate_project_showcase_svg(
            projects, Path(output_path), username=self.client.config.username
        )

    def generate_stats_panel_svg(
        self, language_stats: Dict[str, float], output_path: str
    ) -> None:
        generate_stats_panel_svg(language_stats, Path(output_path))


if __name__ == "__main__":
    sys.exit(main())
