def _build_project_card(project: Dict[str, Any], x_offset: int) -> str:
    name = project.get("name", "Project")
    description = (project.get("description") or "")[:25]
    stars = project.get("stars", 0)
    language = project.get("language", "Unknown")
    return (
        f'<rect x="{x_offset}" y="90" width="200" height="90" rx="10" '
        f'fill="#161b22" stroke="#30363d" stroke-width="1"/>\n'
        f'  <text x="{x_offset + 100}" y="115" text-anchor="middle" '
        f'fill="#58a6ff" font-size="14" font-weight="bold" '
        f'font-family="Arial, sans-serif">{name}</text>\n'
        f'  <text x="{x_offset + 100}" y="135" text-anchor="middle" '
        f'fill="#8b949e" font-size="10" font-family="Arial, sans-serif">'
        f"{description}</text>\n"
        f'  <text x="{x_offset + 100}" y="155" text-anchor="middle" '
        f'fill="#c9d1d9" font-size="11" font-family="Arial, sans-serif">'
        f"⭐ Stars: {stars}</text>\n"
        f'  <text x="{x_offset + 100}" y="170" text-anchor="middle" '
        f'fill="#8b949e" font-size="9" font-family="Arial, sans-serif">'
        f"{language}</text>"
    )


def generate_project_showcase_svg(
    projects: List[Dict[str, Any]],
    output_path: Path,
    username: str,
) -> None:
    """Render ``project-showcase.svg`` to ``output_path``."""
    cards: List[str] = []
    total_stars = 0
    total_forks = 0
    for index, project in enumerate(projects[:MAX_PROJECTS_IN_SHOWCASE]):
        x_offset = 30 + (index * 220)
        cards.append(_build_project_card(project, x_offset))
        total_stars += project.get("stars", 0)
        total_forks += project.get("forks", 0)

    svg = _project_showcase_template().format(
        project_cards="\n  ".join(cards),
        total_projects=len(projects),
        total_stars=total_stars,
        total_forks=total_forks,
        username=username,
    )
    output_path.write_text(svg, encoding="utf-8")
    logger.info("Wrote project showcase SVG to %s", output_path)


